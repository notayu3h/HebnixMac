#!/usr/bin/env bash
# Build + package + publish a HebnixMac release from the current git tag.
# Usage: ./scripts/release-macos.sh v1.1.0
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${HEBNIX_RELEASE_REPO:-$ROOT/../HebnixMac-release}"
TAG="${1:-}"
[ -n "$TAG" ] || { echo "usage: $0 vX.Y.Z"; exit 1; }
case "$TAG" in v*) ;; *) TAG="v$TAG";; esac
VER="${TAG#v}"

echo "== version $VER from tag $TAG =="

# 1. Stamp the fork version into the source so the in-app updater compares
#    against this release. Committed together with the tag.
cat > "$ROOT/hebnix_rs/crates/hebnix-app/src/release_version.rs" <<EOF
// Generated by scripts/release-macos.sh - do not edit by hand.
pub const VERSION: &str = "$VER";
EOF

# 2. Build the app.
"$ROOT/scripts/build-hebnix-app.sh" release

# 3. Package the DMG.
BUILD="$ROOT/build"
cd "$BUILD"
rm -rf dmg-staging HebnixMac.dmg
mkdir -p dmg-staging
cp -R HebnixMac.app dmg-staging/
ln -s /Applications dmg-staging/Applications
hdiutil create -volname "HebnixMac" -srcfolder dmg-staging -ov -format UDZO HebnixMac.dmg >/dev/null
hdiutil verify HebnixMac.dmg >/dev/null

# 4. Mirror sources into the release repo and commit.
mkdir -p "$DEST/releases"
cp -R "$ROOT/hebnix_rs/." "$DEST/hebnix_rs/"
cp -R "$ROOT/macos/." "$DEST/macos/"
cp "$ROOT/scripts/build-hebnix-app.sh" "$ROOT/scripts/make-app-icon.py" "$DEST/scripts/"
cp HebnixMac.dmg "$DEST/releases/"
cd "$DEST"
git add -A
git -c user.name="HebnixMac Release" -c user.email="release@hebnix.local" \
    commit -q -m "Release $TAG" || true

if [ "${PUSH:-0}" = "1" ]; then
    git push -q origin main
    git tag -f "$TAG" && git push -f -q origin "$TAG"
fi

echo "built $BUILD/HebnixMac.dmg (release repo: $DEST)"
echo "next: git push in $DEST, then upload releases/HebnixMac.dmg to the GitHub release"
